"""Tests for the eval harness scoring."""

from pathlib import Path

from datenkatalog_attribute_extractor.models.field import FormField
from datenkatalog_attribute_extractor_tools.acroform import is_generic_name
from datenkatalog_attribute_extractor_tools.eval_models import EvalCase, find_duplicate_names, score_case

CASE_FILE = Path(__file__).resolve().parents[2] / "evals" / "cases" / "example.json"


def make_form_field(name: str, label: str) -> FormField:
    """Build a named field for scoring tests."""
    return FormField(name=name, label=label, context_path=[], page=1)


def make_case(expected: list[str]) -> EvalCase:
    """Build a case with the given expected labels."""
    return EvalCase(name="case", pdf_path=Path("x.pdf"), expected_labels=expected)


def test_score_case_with_a_perfect_run_reports_full_precision_and_recall() -> None:
    case = make_case(["Name:", "Vorname:"])
    fields = [make_form_field("name", "Name:"), make_form_field("vorname", "Vorname:")]

    score = score_case(case, fields)

    assert score.recall == 1.0
    assert score.precision == 1.0
    assert score.f1 == 1.0
    assert score.missing == []
    assert score.unexpected == []


def test_score_case_matches_labels_by_slug_so_colons_and_umlauts_do_not_matter() -> None:
    case = make_case(["Grösse", "Strasse:"])
    fields = [make_form_field("groesse", "Groesse:"), make_form_field("strasse", "Straße")]

    score = score_case(case, fields)

    assert score.recall == 1.0


def test_score_case_reports_missing_and_unexpected_labels() -> None:
    case = make_case(["Name:", "Vorname:"])
    fields = [make_form_field("name", "Name:"), make_form_field("plz", "PLZ:")]

    score = score_case(case, fields)

    assert score.missing == ["vorname"]
    assert score.unexpected == ["plz"]
    assert score.recall == 0.5
    assert score.precision == 0.5


def test_score_case_counts_distinct_labels_but_reports_total_occurrences() -> None:
    case = make_case(["Name:"])
    fields = [make_form_field("vater_name", "Name:"), make_form_field("mutter_name", "Name:")]

    score = score_case(case, fields)

    assert score.expected_count == 1
    assert score.extracted_count == 1
    assert score.total_fields == 2


def test_score_case_with_no_extracted_fields_reports_zero_scores() -> None:
    score = score_case(make_case(["Name:"]), [])

    assert score.recall == 0.0
    assert score.precision == 0.0
    assert score.f1 == 0.0


def test_find_duplicate_names_detects_a_broken_naming_pass() -> None:
    fields = [make_form_field("name", "Name:"), make_form_field("name", "Name:")]

    assert find_duplicate_names(fields) == ["name"]


def test_find_duplicate_names_with_unique_names_returns_nothing() -> None:
    fields = [make_form_field("a", "A"), make_form_field("b", "B")]

    assert find_duplicate_names(fields) == []


def test_bundled_example_case_loads_and_is_curated() -> None:
    case = EvalCase.from_file(CASE_FILE)

    assert case.pdf_path.exists()
    assert len(case.expected_labels) > 40
    assert case.expected_field_count is not None
    assert len(set(case.expected_labels)) == len(case.expected_labels)


def test_is_generic_name_rejects_autogenerated_widget_names() -> None:
    assert is_generic_name("Text1")
    assert is_generic_name("Textfeld 12")
    assert is_generic_name("checkbox-3")
    assert not is_generic_name("Familienname Vater")
    assert not is_generic_name("Sportart")
